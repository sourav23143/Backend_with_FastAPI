
# WE WILL CREATE SHIPMENT SERVICE HERE, IN WHICH WE INTRACT WITH THE DATABASE REGARDING THE SHIPMENTS
from uuid import UUID

from sqlalchemy.ext.asyncio import AsyncSession
from datetime import datetime, timedelta, timezone

from app.database.models import Seller, Shipment
from app.api.schemas.shipment import ShipmentCreate, ShipmentUpdate
from app.database.models import ShipmentStatus
from .base import BaseService
from .delivery_partner import DeliveryPartnerService

class ShipmentService(BaseService):

    def __init__(self, session: AsyncSession, partner_service: DeliveryPartnerService ):
        super().__init__(Shipment, session) # providing model and session to BaseService class


        
        
    # Get the shipment by id
    async def get(self, id: UUID) -> Shipment | None:
        return await self._get(id)


    # Add a new shipment
    async def add(self, shipment_create: ShipmentCreate, seller: Seller) -> Shipment:
        new_shipment = Shipment(
                **shipment_create.model_dump(),
                status = ShipmentStatus.placed,
                estimated_delivery = datetime.now(timezone.utc) + timedelta(days=3), #Time delta is difference b/w two datetime object , And we can use it to create simple difference b/w times as well 
                seller_id=seller.id, #foreign key setup in shipment and relationship as well 
                # seller=seller # insted seller_id=seller.id to work we can directly provide seller as well because we have relationship set up and this will work as well.
            ) # id will get auto generated , when we add this model to the database with default or none ID, it will go ahead and generate a unique id for us, based on maximum number  and we can access it after we commit the changes to our database session
        
        # __________________________________________________________________________________________________________________
        # WHEN WE SUBMIT A NEW SHIPMENT, WE CAN ASSIGN A DELIVERY PARTNER TO HANDLE THE SHIPMENT BASED ON SHIPMENT DESTINATION. DELIVERY
        # PARTNER SHOULD CHECK THE SAME I.E ZIP CODE IN OUR DATABASE
        # __________________________________________________________________________________________________________________
        partner = await self.partner_service.assign_shipment(new_shipment)
        new_shipment.delivery_partner_id = partner.id
        # once the delivery partner is aasigned we can add it to database and return the newly created shipment

        
        # self.session.add(new_shipment) # for add method we not have to wait, as it return None, not a coroutine, so no await 
        # await self.session.commit()
        # await self.session.refresh(new_shipment) # refreshing the new shipment object to get the new id generated by the database, and now we can access it as new_shipment.id as before it was by default it was None, beacuse we created it here only 
        
        return await self._add(new_shipment)

        
    # Update an existing shipment
    async def update(self, id: int, shipment_update: dict) -> Shipment:
        shipment = await self.get(id)
        shipment.sqlmodel_update(shipment_update)
        
        
        return await self._update(shipment)

    # Delete a shipment
    async def delete(self, id: int) -> None:
        # Remove from database
        await self._delete(self.get(id))
