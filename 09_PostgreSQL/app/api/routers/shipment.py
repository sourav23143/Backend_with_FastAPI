### Update shipment by id
@router.patch("/", response_model=ShipmentRead)
async def update_shipment(
    id: int, shipment_update: ShipmentUpdate, service: ShipmentServiceDep
) -> dict[str, Any]:

    # Update data with given fields

    update = shipment_update.model_dump(
        exclude_none=True
    )  # we will exclude the fields which are None, because we dont want to update those fields in our database, and we will only update the fields which are provided in the request body, and we will use model_dump to convert the pydantic model to a dictionary, and then we will use this dictionary to update our database

    if (
        not update
    ):  # if update is empty, i.e no fields to update, then we will raise an error
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="No data provided to update!",
        )

    shipment = await service.update(id, update)

    return shipment


