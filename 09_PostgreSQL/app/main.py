@app.get("/shipment", response_model = ShipmentRead) #hinting resonse model > WE USE IT WHEN WE ARE PROVIDING DIFFERENT TYPE, IN THIS CASE A LOOSELY TYPE DICTIONARY AND WE WANT TO IT VALIDATED AGAINST THIS SCHEMA
def get_shipment(id: int, session: SessionDep):  # we will use session to get data from our database #  FASTAPI WILL READ THE DATA FROM THE METADATA OF OUR ANNOTED TYPE
    # Check for shipment with given id 
    shipment = session.get(Shipment, id)
    # shipment.c #with this we get shipment object and we can access all the fields of this shipment object, i.e content, weight, destination, status and estimated_delivery# 
    
    if shipment is None:
        raise HTTPException(
            #inside it we will provide our status code as well as error details
            status_code=status.HTTP_404_NOT_FOUND,
            detail = "Given id doesn't exist!"
        )
    return  shipment



@app.post("/shipment")
def submit_shipment(shipment: ShipmentCreate, session: SessionDep) -> dict[str, Any]:  

    new_shipment = Shipment(
        **shipment.model_dump(),
        status = ShipmentStatus.placed,
        estimated_delivery = datetime.now(timezone.utc) + timedelta(days=3) #Time delta is difference b/w two datetime object , And we can use it to create simple difference b/w times as well 
    ) # id will get auto generated , when we add this model to the database with default or none ID, it will go ahead and generate a unique id for us, based on maximum number  and we can access it after we commit the changes to our database session

    session.add(new_shipment) # adding new shipment to our database session
    session.commit() # commiting the changes to our database session
    session.refresh(new_shipment) # refreshing the new shipment object to get the new id generated by the database, and now we can access it as new_shipment.id as before it was by default it was None, beacuse we created it here only 



    return {"id": new_shipment.id, "detail": "Shipment submitted successfully!"} # returning the new shipment id and success message





@app.patch("/shipment", response_model = ShipmentRead)
def update_shipment(
    id: int, 
    shipment_update: ShipmentUpdate,
    session: SessionDep
    ) -> dict[str, Any]:

    # Update data with given fields

    update = shipment_update.model_dump(exclude_none=True) # we will exclude the fields which are None, because we dont want to update those fields in our database, and we will only update the fields which are provided in the request body, and we will use model_dump to convert the pydantic model to a dictionary, and then we will use this dictionary to update our database


    if not update: # if update is empty, i.e no fields to update, then we will raise an error
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail = "No data provided to update!"
        )


    shipment =  session.get(Shipment, id)
    shipment.sqlmodel_update(update)


    session.add(shipment)
    session.commit()
    session.refresh(shipment) # refreshing the shipment object to get the updated data from the database

    return shipment



@app.delete("/shipment")
def delete_shipment(id: int, session: SessionDep) -> dict[str, str]:
    # Remove from database
    session.delete(
        session.get(Shipment, id)
    )
    session.commit()
    return {"detail": f"Shipment with id #{id} is deleted!"}






